// Regenerate src/core/prompts.generated.ts from the .md section sources in
// src/core/prompts/. Deterministic: same inputs → byte-identical output
// (sorted keys, no timestamps). Run after editing any .md source:
//   node scripts/gen-prompts.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const srcDir = fileURLToPath(new URL('../src/core/prompts', import.meta.url))
const outFile = fileURLToPath(new URL('../src/core/prompts.generated.ts', import.meta.url))

/** Serialize a string in the repo's biome-canonical form: single quotes,
 *  minimal escapes (' and \ plus control chars). Printable non-ASCII stays raw. */
function tsString(value) {
  let out = "'"
  for (const ch of value) {
    if (ch === "'") out += "\\'"
    else if (ch === '\\') out += '\\\\'
    else if (ch === '\n') out += '\\n'
    else if (ch === '\r') out += '\\r'
    else if (ch === '\t') out += '\\t'
    else out += ch
  }
  return `${out}'`
}

/** Object key: bare when it is a valid identifier, quoted otherwise
 *  (stable under both preserve and as-needed quote semantics). */
function tsKey(id) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(id) ? id : tsString(id)
}

const entries = readdirSync(srcDir)
  .filter((name) => name.endsWith('.md'))
  .sort()
  .map((name) => {
    const id = name.slice(0, -'.md'.length)
    // Trailing whitespace is trimmed so a trailing newline in the .md source
    // never leaks into the section body.
    const body = readFileSync(join(srcDir, name), 'utf8').replace(/\s+$/, '')
    return { id, body }
  })

const lines = [
  '// GENERATED by scripts/gen-prompts.mjs — edit .md sources, run node scripts/gen-prompts.mjs',
  'export const PROMPT_BODIES: Readonly<Record<string, string>> = {',
]
for (const { id, body } of entries) {
  lines.push(`  ${tsKey(id)}: ${tsString(body)},`)
}
lines.push('}')

writeFileSync(outFile, `${lines.join('\n')}\n`)
console.log(`gen-prompts: ${entries.length} sections -> src/core/prompts.generated.ts`)
